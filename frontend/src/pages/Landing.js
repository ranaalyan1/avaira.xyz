import { useEffect, useRef, useState } from "react";
import { useNavigate, Link } from "react-router-dom";
import { useAuth } from "@/App";
import { useReveal, prefersReducedMotion } from "@/lib/motion";
import { lazy, Suspense } from "react";
import {
  ImmersiveNav, ImmersiveFoot, RefusalTicker, LAYERS,
  usePageTitle,
} from "@/pages/immersive/shell";
import { useHeroChoreo } from "@/lib/choreo";
import { useAuthUI } from "@/components/auth/AuthUIContext";

/* the 3D gate code-splits with the R3F/three payload — the page text paints
 * first, jest static renders never evaluate WebGL, and a failed chunk load
 * degrades to the CSS poster below. */
const GateScene = lazy(() => import("@/components/marketing/immersive/GateScene"));
const GatePoster = () => (
  <div className="imm-canvas-poster" aria-hidden="true"><span /><span /><span /></div>
);

/* Home — Act I (thesis), Act II (problem), Act III (the boundary scrollytelling)
 * and Act VIII (the invitation). The rest of the narrative lives on its own
 * routes: /execution and /evidence. Every claim on this page is regenerated by
 * a make target in this repository or read from
 * contracts/deployments/4663.json. Nothing here is a price, no metric is
 * invented, and the testnet status is labelled as testnet. The 3D canvas never
 * carries essential text: labels, reasons and addresses all live in semantic
 * HTML. */

export default function Landing() {
  const { user } = useAuth();
  const navigate = useNavigate();
  const revealRoot = useReveal();
  useHeroChoreo(revealRoot);
  usePageTitle("AVAIRA — Nothing spends until the gate returns a permit");

  /* scrollytelling state — refs, not re-renders, at 60fps */
  const trackRef = useRef(null);
  const explodedRef = useRef(0);
  const barRef = useRef(null);
  const [layer, setLayer] = useState(0);
  /* the sticky Act III scene mounts only on >=768px viewports — on small
   * screens the layers read in sequence as plain cards (see the CSS) */
  const [wideBoundary, setWideBoundary] = useState(() =>
    typeof window !== "undefined" && typeof window.matchMedia === "function" && window.matchMedia("(min-width: 768px)").matches);
  useEffect(() => {
    if (typeof window === "undefined" || !window.matchMedia) return undefined;
    const mq = window.matchMedia("(min-width: 768px)");
    const on = () => setWideBoundary(mq.matches);
    mq.addEventListener("change", on);
    return () => mq.removeEventListener("change", on);
  }, []);

  useEffect(() => {
    const track = trackRef.current;
    let raf = 0;
    const onScroll = () => {
      cancelAnimationFrame(raf);
      raf = requestAnimationFrame(() => {
        /* global page progress for the top bar */
        const doc = document.documentElement;
        const pageP = Math.min(1, window.scrollY / Math.max(1, doc.scrollHeight - window.innerHeight));
        if (barRef.current) barRef.current.style.width = `${pageP * 100}%`;
        /* boundary scrollytelling */
        if (!track || prefersReducedMotion()) return;
        const r = track.getBoundingClientRect();
        const total = r.height - window.innerHeight;
        const p = Math.min(1, Math.max(0, -r.top / Math.max(1, total)));
        explodedRef.current = p;
        setLayer(Math.min(LAYERS.length - 1, Math.floor(p * LAYERS.length * 0.999)));
      });
    };
    window.addEventListener("scroll", onScroll, { passive: true });
    onScroll();
    return () => { window.removeEventListener("scroll", onScroll); cancelAnimationFrame(raf); };
  }, []);

  const go = (path) => () => navigate(user ? path : `/login?redirect=${encodeURIComponent(path)}`);
  const { openAuth } = useAuthUI();

  return (
    <div className="landing-immersive" data-testid="landing-page" ref={revealRoot}>
      <a href="#hero" className="sr-only focus:not-sr-only">Skip to content</a>
      <div className="imm-progressbar" aria-hidden="true"><i ref={barRef} /></div>

      <ImmersiveNav />

      <main className="imm-page" id="hero">
        {/* Act I — the thesis */}
        <header className="imm-hero" data-testid="hero-section">
          <div className="imm-hero-canvas">
            <Suspense fallback={<GatePoster />}>
              <GateScene progressRef={explodedRef} />
            </Suspense>
          </div>
          <div className="imm-hud" aria-hidden="true">
            <p>ROBINHOOD TESTNET <b>/ CHAIN 46630</b></p>
            <p>GATE <b>OPERATIONAL</b> / REFUSALS 9</p>
            <p>SETTLEMENT <b>24H CHALLENGE WINDOW</b></p>
          </div>
          <span className="imm-corner tl" aria-hidden="true" />
          <span className="imm-corner br" aria-hidden="true" />
          <div className="imm-hero-copy">
            <p className="imm-label" style={{ marginBottom: "1.4rem" }}>Act 01 <em>— onchain accountability for AI agents</em></p>
            <h1 className="imm-display">
              An agent proposes.
              <br />
              <em>Avaira</em> verifies.
            </h1>
            <p className="imm-lead" style={{ margin: "1.6rem 0 2rem" }}>
              Every action is committed before it runs, gated against identity, stake
              and score, and settled with evidence anyone can re-read onchain.
              Built for Robinhood Chain.
            </p>
            <div style={{ display: "flex", gap: "0.8rem", flexWrap: "wrap" }}>
              <Link className="imm-btn imm-btn-primary" data-testid="hero-launch-btn" to="/execution">
                Follow the execution
              </Link>
              {user ? (
                <button type="button" className="imm-btn imm-btn-ghost" onClick={go("/dashboard")}>
                  Open console
                </button>
              ) : (
                <button type="button" className="imm-btn imm-btn-ghost" data-testid="hero-login-btn" onClick={openAuth}>
                  Sign in
                </button>
              )}
            </div>
          </div>
          <p className="imm-label imm-scrollhint">Scroll — the boundary explains itself</p>
        </header>

        <RefusalTicker />

        {/* Act II — the problem */}
        <section className="imm-act" data-testid="problem-section" aria-labelledby="problem-h">
          <div className="imm-act-head">
            <p className="imm-label">Act 02 <em>— the problem</em></p>
            <h2 className="imm-h2" id="problem-h" data-reveal>
              Between a proposal and an action there is usually nothing.
            </h2>
            <p className="imm-lead" data-reveal>
              An agent asks to move funds, call a tool, spend a budget. In most
              stacks the request goes straight through. The prompt is the only
              policy, the logs are the only evidence, and both can be edited after
              the fact by the same party that ran the action.
            </p>
            <p className="imm-body" data-reveal>
              Avaira makes the gap a boundary: a place where authorization is
              decided by contracts, not by confidence, and where the record of the
              decision cannot be rewritten by anyone, including us.
            </p>
          </div>
        </section>

        {/* Act III — the boundary (scrollytelling) */}
        <section className="imm-boundary" id="boundary" data-testid="boundary-section" aria-labelledby="boundary-h">
          <h2 className="sr-only" id="boundary-h">The execution boundary, layer by layer</h2>
          <div className="imm-boundary-track" ref={trackRef}>
            <div className="imm-boundary-stage">
              <div className="imm-boundary-canvas">
                {wideBoundary ? (
                  <Suspense fallback={<GatePoster />}>
                    <GateScene progressRef={explodedRef} />
                  </Suspense>
                ) : null}
              </div>
              <div className="imm-progress" aria-hidden="true">
                {LAYERS.map((l, i) => (
                  <span key={l.key} className={`imm-progress-dot${i === layer ? " imm-dot-on" : ""}`} />
                ))}
              </div>
              {LAYERS.map((l, i) => (
                <article
                  key={l.key}
                  className={`imm-layer${i === layer ? " imm-layer-on" : ""}`}
                  data-testid={`boundary-act-${l.key}`}
                  aria-hidden={i === layer ? undefined : "true"}
                >
                  <p className="imm-label">{`Gate layer ${l.no}`}</p>
                  <h3>{l.name}</h3>
                  <p className="imm-body">{l.body}</p>
                  <p className="imm-reason">{`reverts: ${l.reason}`}</p>
                </article>
              ))}

            </div>
          </div>
        </section>

        {/* Act VIII — the invitation */}
        <section className="imm-cta" id="cta" data-testid="cta-section" aria-labelledby="cta-h">
          <div>
            <p className="imm-label">Act 08 <em>— the invitation</em></p>
            <h2 className="imm-h2" id="cta-h" style={{ margin: "0.8rem 0 1rem" }} data-reveal>
              Build agents that can prove what they did.
            </h2>
            <p className="imm-lead" style={{ margin: "0 auto" }} data-reveal>
              The protocol, the tests, the audit package and the deployment record
              are all public. Read the mechanics before you trust a single word
              of this page, that is the point.
            </p>
          </div>
          <div className="imm-cta-actions" data-reveal>
            <Link className="imm-btn imm-btn-primary" data-testid="cta-launch-btn" to="/gate">
              See the gate mechanics
            </Link>
            <a className="imm-btn imm-btn-ghost" href="https://github.com/ranaalyan1/avaira.xyz">
              Read the source
            </a>
            <Link className="imm-btn imm-btn-ghost" to="/docs">
              Integrate the SDK
            </Link>
          </div>
        </section>
      </main>

      <ImmersiveFoot />
    </div>
  );
}
