#!/usr/bin/env python3
"""Render the README's deployed-contract section from `deployments/{chainId}.json`.

The README cannot be allowed to advertise an address that no command verified.
This generator makes the section a *projection* of the deployment manifest rather
than a paragraph someone edits by hand, so the two cannot disagree:

    python3 tools/gen_deploy_section.py            # rewrite README from the manifest
    python3 tools/gen_deploy_section.py --check     # exit 1 if the section is stale

The manifest is written by `make deploy-monad` and checked by `make verify-monad`.
While it does not exist, the section says exactly that — no addresses, no
placeholder hex — and points at the three-step deploy path plus the no-key
dry-run.

`--check` is what keeps it honest later: it re-renders and compares, so a
hand-edited address or a stale copy fails loudly instead of shipping.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
BEGIN = "<!-- BEGIN:deployed-contracts (generated by tools/gen_deploy_section.py — do not edit) -->"
END = "<!-- END:deployed-contracts -->"

EXPLORER = {10143: "https://testnet.monadscan.com", 143: "https://monadscan.com"}
NETWORK = {10143: "Monad Testnet", 143: "Monad Mainnet"}

# manifest key → the name used in the README table
CONTRACTS = [
    ("identityRegistry", "AvairaIdentityRegistry", "ERC-8004 identity + bonds"),
    ("reputationRegistry", "AvairaReputationRegistry", "Avaira Score, grounded feedback"),
    ("validationRegistry", "AvairaValidationRegistry", "validator attestations"),
    ("stakeRegistry", "AvairaStakeRegistry", "stake, slashing, suspension"),
    ("intentVault", "AvairaIntentVault", "pre-execution gate, challenges"),
    ("creditMarket", "AvairaCreditMarket", "tiered credit against score"),
    ("settlementToken", "MockUSDC", "6-decimal settlement token"),
]


def render(chain_id: int, manifest: dict | None) -> str:
    # BEGIN has to be part of the rendered block: splice() replaces
    # BEGIN…END inclusive, so a block without it would delete the marker on the
    # first run and make every later --check fail.
    lines = [BEGIN, "## 📍 Deployed Contracts (Monad Testnet)", ""]

    if manifest is None:
        lines += [
            f"**Not deployed yet.** `deployments/{chain_id}.json` does not exist, so there are no",
            "addresses to publish — this section renders only what that file contains, which is why it",
            "cannot drift from reality.",
            "",
            "```bash",
            "# 1. fund a wallet                      https://faucet.monad.xyz",
            "# 2. cd contracts && cp .env.example .env   → set DEPLOYER_PRIVATE_KEY=0x…",
            "# 3. make deploy-monad                  writes deployments/10143.json",
            "",
            "make deploy-dry-run   # proves the wiring in-process first; spends nothing",
            "make verify-monad     # fails loudly until the addresses above are live",
            "```",
        ]
        lines += ["", END]
        return "\n".join(lines)

    network = NETWORK.get(chain_id, f"chain {chain_id}")
    explorer = EXPLORER.get(chain_id, "")
    txs = manifest.get("deploymentTxs") or {}
    lines += [
        f"**{network}** (chain id `{chain_id}`) — every address below is read from",
        f"[`deployments/{chain_id}.json`](deployments/{chain_id}.json), and `make verify-monad` asserts",
        "each one has bytecode and that its getters point at the right siblings.",
        "",
        "| Contract | Address | What it holds | Deploy tx |",
        "| :--- | :--- | :--- | :--- |",
    ]
    for key, name, role in CONTRACTS:
        address = manifest.get(key)
        if not address:
            lines.append(f"| `{name}` | _missing from the manifest_ | {role} | — |")
            continue
        link = f"[`{address}`]({explorer}/address/{address})" if explorer else f"`{address}`"
        tx = txs.get(name)
        tx_cell = f"[`{tx[:10]}…`]({explorer}/tx/{tx})" if (tx and explorer) else (f"`{tx[:10]}…`" if tx else "—")
        lines.append(f"| `{name}` | {link} | {role} | {tx_cell} |")

    lines += [""]
    extra = [
        ("deployer", manifest.get("deployer")),
        ("deployment block", manifest.get("deploymentBlock")),
    ]
    rendered = [f"{label} `{value}`" for label, value in extra if value not in (None, "")]
    if len(txs) < len(CONTRACTS):
        rendered.append(f"deploy tx hashes for {len(txs)}/{len(CONTRACTS)} contracts (run `tools/merge_deploy_txs.py`)")
    if rendered:
        lines += [" · ".join(rendered), ""]
    lines += [
        "Reproduce:",
        "",
        "```bash",
        "make deploy-dry-run   # the same deployment in-process, no funds",
        "make verify-monad     # liveness + wiring, straight from the RPC",
        "```",
        "",
        END,
    ]
    return "\n".join(lines)


def splice(readme: str, section: str) -> str:
    if BEGIN not in readme or END not in readme:
        raise SystemExit(f"README.md is missing the {BEGIN} … {END} markers")
    head, rest = readme.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{section}{tail}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--chain", type=int, default=10143)
    ap.add_argument("--check", action="store_true", help="exit 1 if the README section is stale")
    args = ap.parse_args(argv)

    manifest_path = ROOT / "deployments" / f"{args.chain}.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else None
    section = render(args.chain, manifest)

    current = README.read_text()
    updated = splice(current, section)

    if args.check:
        if updated != current:
            print("README deployed-contracts section is stale — run: python3 tools/gen_deploy_section.py")
            return 1
        state = "deployed" if manifest else "not deployed"
        print(f"README deployed-contracts section matches deployments/{args.chain}.json ({state})")
        return 0

    if updated == current:
        print(f"README already current ({'deployed' if manifest else 'not deployed'})")
        return 0
    README.write_text(updated)
    print(f"README deployed-contracts section rewritten from deployments/{args.chain}.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
